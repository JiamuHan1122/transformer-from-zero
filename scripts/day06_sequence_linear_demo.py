"""Day 06 milestone demo: train a shared 3D linear layer on token sequences.

Run from the repository root:
    conda activate tfz
    python scripts/day06_sequence_linear_demo.py

The demo uses your own NumPy implementations:
- exercises.week06.linear_3d_numpy
- exercises.week06.linear_3d_mse_gradients
- exercises.week03.finite_difference_gradient

No torch autograd or torch optimizer is used for training.

Generated local outputs (ignored by Git):
    results/day06/metrics.json
    results/day06/loss_curve.png
    results/day06/sequence_prediction_comparison.png
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from exercises.week03 import finite_difference_gradient  # noqa: E402
from exercises.week06 import (  # noqa: E402
    linear_3d_mse_gradients,
    linear_3d_numpy,
)


def half_mse(predictions: np.ndarray, targets: np.ndarray) -> float:
    """Sum feature errors per token, then average over B*T tokens."""
    batch_size, sequence_length = predictions.shape[:2]
    error = predictions - targets
    return float(0.5 * np.sum(error**2) / (batch_size * sequence_length))


def relative_error(analytic: np.ndarray, numeric: np.ndarray) -> float:
    denominator = max(
        1e-12,
        float(np.linalg.norm(analytic) + np.linalg.norm(numeric)),
    )
    return float(np.linalg.norm(analytic - numeric) / denominator)


def check_3d_gradients(
    x: np.ndarray,
    weight: np.ndarray,
    bias: np.ndarray,
    targets: np.ndarray,
) -> dict[str, float]:
    """Independently compare hand-derived gradients with central differences."""
    _, analytic_weight, analytic_bias = linear_3d_mse_gradients(
        x, weight, bias, targets
    )
    token_count = x.shape[0] * x.shape[1]

    def loss_with_weight(candidate_weight: np.ndarray) -> float:
        predictions = linear_3d_numpy(x, candidate_weight, bias)
        return half_mse(predictions, targets)

    def loss_with_bias(candidate_bias: np.ndarray) -> float:
        predictions = linear_3d_numpy(x, weight, candidate_bias)
        return half_mse(predictions, targets)

    numeric_weight = finite_difference_gradient(
        loss_with_weight, weight, epsilon=1e-5
    )
    numeric_bias = finite_difference_gradient(
        loss_with_bias, bias, epsilon=1e-5
    )

    return {
        "weight": relative_error(analytic_weight, numeric_weight),
        "bias": relative_error(analytic_bias, numeric_bias),
        "token_count": float(token_count),
    }


def main() -> None:
    output_dir = ROOT / "results" / "day06"
    output_dir.mkdir(parents=True, exist_ok=True)

    # Each token is generated by the SAME ground-truth linear projection.
    # The validation sequences are sampled independently from training data.
    rng = np.random.default_rng(606)
    batch_size, sequence_length, input_dim, output_dim = 16, 8, 4, 3

    x_train = rng.normal(
        0.0, 1.0, size=(batch_size, sequence_length, input_dim)
    ).astype(np.float64)
    x_valid = rng.normal(
        0.0, 1.0, size=(4, sequence_length, input_dim)
    ).astype(np.float64)

    true_weight = rng.normal(
        0.0, 0.7, size=(input_dim, output_dim)
    ).astype(np.float64)
    true_bias = np.array([0.35, -0.25, 0.15], dtype=np.float64)

    y_train = linear_3d_numpy(x_train, true_weight, true_bias)
    y_valid = linear_3d_numpy(x_valid, true_weight, true_bias)

    initial_weight = rng.normal(
        0.0, 0.5, size=(input_dim, output_dim)
    ).astype(np.float64)
    initial_bias = rng.normal(0.0, 0.3, size=(output_dim,)).astype(np.float64)

    learning_rate = 0.08
    steps = 200
    checkpoints = [0, 1, 2, 5, 10, 20, 50, 100, 150, 200]

    print("=" * 78)
    print("Transformer From Zero | Day 06 | 3D Sequence Linear Training Demo")
    print("=" * 78)
    print("Synthetic task: every token follows y_token = x_token @ W_true + b_true")
    print(
        f"Train shape: {x_train.shape} | Validation shape: {x_valid.shape}"
    )
    print(
        f"Shared parameters: {input_dim * output_dim + output_dim} "
        f"(W: {input_dim * output_dim}, b: {output_dim})"
    )
    print(f"Learning rate: {learning_rate} | Gradient updates: {steps}")

    # First verify the analytical 3D gradients independently.
    gradient_errors = check_3d_gradients(
        x_train, initial_weight, initial_bias, y_train
    )
    print("\nIndependent gradient check (central finite differences):")
    print(f"  weight relative error: {gradient_errors['weight']:.3e}")
    print(f"  bias relative error:   {gradient_errors['bias']:.3e}")
    if any(
        not np.isfinite(gradient_errors[name])
        or gradient_errors[name] >= 1e-6
        for name in ("weight", "bias")
    ):
        raise RuntimeError(
            "3D gradient check failed. Inspect linear_3d_mse_gradients."
        )

    # Train only with the hand-derived NumPy gradients from Week 06.
    weight = initial_weight.copy()
    bias = initial_bias.copy()
    loss_history: list[float] = []

    print("\nTraining history:")
    print(f"{'Step':>6} | {'Train loss':>18} | {'Validation loss':>18}")
    print("-" * 50)

    for step in range(steps + 1):
        train_loss, grad_weight, grad_bias = linear_3d_mse_gradients(
            x_train, weight, bias, y_train
        )
        valid_loss = half_mse(
            linear_3d_numpy(x_valid, weight, bias), y_valid
        )
        loss_history.append(float(train_loss))

        if step in checkpoints:
            print(f"{step:6d} | {train_loss:18.10e} | {valid_loss:18.10e}")

        if step == steps:
            break

        # Both gradients were computed from the same pre-update parameters.
        weight -= learning_rate * grad_weight
        bias -= learning_rate * grad_bias

    final_train_loss = float(loss_history[-1])
    final_valid_loss = half_mse(
        linear_3d_numpy(x_valid, weight, bias), y_valid
    )
    initial_train_loss = float(loss_history[0])
    initial_valid_loss = half_mse(
        linear_3d_numpy(x_valid, initial_weight, initial_bias), y_valid
    )

    initial_train_prediction = linear_3d_numpy(
        x_train, initial_weight, initial_bias
    )
    trained_train_prediction = linear_3d_numpy(x_train, weight, bias)
    trained_valid_prediction = linear_3d_numpy(x_valid, weight, bias)

    print("\nParameter recovery:")
    print(
        f"  max |W_trained - W_true|: "
        f"{np.max(np.abs(weight - true_weight)):.6e}"
    )
    print(
        f"  max |b_trained - b_true|: "
        f"{np.max(np.abs(bias - true_bias)):.6e}"
    )

    print("\nBefore / after:")
    print(
        f"  train loss: {initial_train_loss:.10e} -> "
        f"{final_train_loss:.10e}"
    )
    print(
        f"  valid loss: {initial_valid_loss:.10e} -> "
        f"{final_valid_loss:.10e}"
    )

    # Show a few token predictions from one held-out sequence.
    print("\nValidation sequence 0 — selected token predictions:")
    print(f"{'Token':>7} | {'Target':>30} | {'Trained prediction':>30}")
    print("-" * 76)
    for token_index in (0, 2, 4, 7):
        target_values = np.array2string(
            y_valid[0, token_index], precision=5, suppress_small=True
        )
        prediction_values = np.array2string(
            trained_valid_prediction[0, token_index],
            precision=5,
            suppress_small=True,
        )
        print(
            f"{token_index:7d} | {target_values:>30} | "
            f"{prediction_values:>30}"
        )

    metrics = {
        "project": "Transformer From Zero - Day 06",
        "experiment": "Shared 3D linear projection on token sequences",
        "seed": 606,
        "train_shape": list(x_train.shape),
        "validation_shape": list(x_valid.shape),
        "input_dim": input_dim,
        "output_dim": output_dim,
        "shared_parameter_count": int(weight.size + bias.size),
        "learning_rate": learning_rate,
        "steps": steps,
        "loss_definition": "0.5 * sum(error**2) / (B*T); sum H, average B*T",
        "gradient_check_relative_errors": {
            "weight": gradient_errors["weight"],
            "bias": gradient_errors["bias"],
        },
        "initial": {
            "train_loss": initial_train_loss,
            "validation_loss": initial_valid_loss,
        },
        "final": {
            "train_loss": final_train_loss,
            "validation_loss": final_valid_loss,
            "max_abs_weight_error": float(np.max(np.abs(weight - true_weight))),
            "max_abs_bias_error": float(np.max(np.abs(bias - true_bias))),
        },
        "loss_checkpoints": {
            str(step): float(loss_history[step]) for step in checkpoints
        },
    }
    metrics_path = output_dir / "metrics.json"
    metrics_path.write_text(
        json.dumps(metrics, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"\nSaved: {metrics_path.relative_to(ROOT)}")

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("\nMatplotlib is not installed. Install it with:")
        print("  python -m pip install matplotlib")
        print("Metrics were saved; PNG figures were not generated.")
    else:
        # Figure 1: loss decreases on both training and unseen sequences.
        validation_history = []
        plot_weight = initial_weight.copy()
        plot_bias = initial_bias.copy()
        for step in range(steps + 1):
            validation_history.append(
                half_mse(
                    linear_3d_numpy(x_valid, plot_weight, plot_bias),
                    y_valid,
                )
            )
            if step == steps:
                break
            _, plot_grad_weight, plot_grad_bias = linear_3d_mse_gradients(
                x_train, plot_weight, plot_bias, y_train
            )
            plot_weight -= learning_rate * plot_grad_weight
            plot_bias -= learning_rate * plot_grad_bias

        fig, ax = plt.subplots(figsize=(9, 5))
        ax.semilogy(
            np.arange(steps + 1),
            np.maximum(loss_history, 1e-16),
            label="Training sequences",
            linewidth=2.2,
        )
        ax.semilogy(
            np.arange(steps + 1),
            np.maximum(validation_history, 1e-16),
            label="Unseen validation sequences",
            linewidth=2.2,
        )
        ax.set(
            title="Day 06 | Shared 3D Linear Layer Training",
            xlabel="Gradient update",
            ylabel="Loss (log scale)",
        )
        ax.grid(True, alpha=0.22)
        ax.legend()
        fig.tight_layout()
        loss_path = output_dir / "loss_curve.png"
        fig.savefig(loss_path, dpi=180)
        plt.close(fig)

        # Figure 2: compare target, initial and trained predictions for one
        # held-out sequence, separately for each output feature.
        sequence_index = 0
        initial_valid_prediction = linear_3d_numpy(
            x_valid, initial_weight, initial_bias
        )
        fig, axes = plt.subplots(
            output_dim, 1, figsize=(9, 2.8 * output_dim), sharex=True
        )
        axes = np.atleast_1d(axes)
        token_positions = np.arange(sequence_length)

        for feature_index, ax in enumerate(axes):
            ax.plot(
                token_positions,
                y_valid[sequence_index, :, feature_index],
                marker="o",
                linewidth=2,
                label="Ground truth",
            )
            ax.plot(
                token_positions,
                initial_valid_prediction[sequence_index, :, feature_index],
                linestyle="--",
                marker="x",
                label="Before training",
            )
            ax.plot(
                token_positions,
                trained_valid_prediction[sequence_index, :, feature_index],
                marker=".",
                linewidth=2,
                label="After training",
            )
            ax.set_ylabel(f"Feature {feature_index}")
            ax.grid(True, alpha=0.22)
            ax.legend(loc="best")

        axes[-1].set_xlabel("Token position")
        fig.suptitle(
            "Day 06 | Predictions Across One Unseen Sequence", y=1.01
        )
        fig.tight_layout()
        prediction_path = output_dir / "sequence_prediction_comparison.png"
        fig.savefig(prediction_path, dpi=180, bbox_inches="tight")
        plt.close(fig)

        print(f"Saved: {loss_path.relative_to(ROOT)}")
        print(f"Saved: {prediction_path.relative_to(ROOT)}")

    if (
        final_train_loss < initial_train_loss * 1e-5
        and final_valid_loss < initial_valid_loss * 1e-5
        and np.max(np.abs(weight - true_weight)) < 1e-3
        and np.max(np.abs(bias - true_bias)) < 1e-3
    ):
        print(
            "\nSUCCESS: the hand-written 3D linear layer learned one shared "
            "mapping across all tokens."
        )
    else:
        raise RuntimeError(
            "Training did not meet the demo thresholds. Inspect the metrics "
            "and gradient implementation before drawing conclusions."
        )


if __name__ == "__main__":
    main()
